"""Step 5: every number in post.qmd. Reads output/ (and CLASS for three row-level counts).

Writes:
  _variables.yml          values for {{< var ... >}} in post.qmd (Quarto reads it from the post's folder)
  output/tables/*.md      Markdown tables included in post.qmd

Usage: python -I step5_numbers.py
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))  # run under python -I
from load_data import ROOT, load_house, load_all
import step4_skill_source as s4

OUT = ROOT / "output"
TAB = OUT / "tables"
EXP = OUT / "exploratory"


def f2(x): return f"{x:.2f}"
def f3(x): return f"{x:.3f}"
def f5(x): return f"{x:.5f}"
def n(x): return f"{int(x):,}"
def ci3(lo, hi): return f"[{lo:.3f}, {hi:.3f}]"
def sgn3(x): return f"{x:+.3f}".replace("-", "−")
def ci3s(lo, hi): return f"[{sgn3(lo)}, {sgn3(hi)}]"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def write_yaml(d, path):
    lines = ["# GENERATED by code/step5_numbers.py from output/. Do not edit by hand."]
    for sec, kv in d.items():
        lines.append(f"{sec}:")
        for k, v in kv.items():
            lines.append(f'  {k}: "{v}"')
    path.write_text("\n".join(lines) + "\n")


def main():
    TAB.mkdir(parents=True, exist_ok=True)
    s3 = json.loads((OUT / "step3_results.json").read_text())["bodies"]
    s4r = json.loads((OUT / "step4_results.json").read_text())
    co = pd.read_csv(OUT / "step4_coefs.csv")
    lr = json.loads((EXP / "expl_law_results.json").read_text())
    mixed = pd.read_csv(EXP / "expl_law_mixed.csv").set_index(["body", "quantity"])
    units = pd.read_csv(EXP / "expl_law_units.csv")
    rank = json.loads((EXP / "expl_rank_house.json").read_text())
    V = {}

    # ---- Step 3 (PREREG) ----
    raw_house = load_house()
    V["data"] = {"house_dropped_no_icpsr": n(raw_house["id"].isna().sum()),
                 "house_rows_raw": n(len(raw_house))}
    for b, key in [("House", "house"), ("Senate", "senate"), ("States", "states")]:
        r = s3[b]
        V[key] = {"rows": n(r["n_rows"]), "members": n(r["n_members"]), "mean_terms": f2(r["mean_terms_per_member"]),
                  "t_min": str(r["t_min"]), "t_max": str(r["t_max"]),
                  "kappa": f3(r["kappa"]), "kappa_lo": f3(r["kappa_lo"]), "kappa_hi": f3(r["kappa_hi"]),
                  "kappa_lo5": f5(r["kappa_lo"]),
                  "sig2_alpha": f3(r["sig2_alpha"]), "sig2_eps": f3(r["sig2_eps"]), "sigma_alpha": f3(r["sigma_alpha"]),
                  "r2": f3(r["marginal_r2"]), "r2_lo": f3(r["marginal_r2_lo"]), "r2_hi": f3(r["marginal_r2_hi"]),
                  "share_x": f2(r["share_x"]), "share_alpha": f2(r["share_alpha"]), "share_eps": f2(r["share_eps"]),
                  "r": f3(r["oos_r"]), "r_lo": f3(r["oos_r_lo"]), "r_hi": f3(r["oos_r_hi"]),
                  "oos_pairs": n(r["oos_n_pairs"]), "oos_members": n(r["oos_n_members"]),
                  "verdict": r["prereg_verdict"]}
        tab = md_table(["Quantity", "Estimate", "95% CI"], [
            ["κ = σ²_α / (σ²_α + σ²_ε)", f3(r["kappa"]), ci3(r["kappa_lo"], r["kappa_hi"])],
            ["σ²_α (between members)", f3(r["sig2_alpha"]), ci3(r["sig2_alpha_lo"], r["sig2_alpha_hi"])],
            ["σ²_ε (within member, term to term)", f3(r["sig2_eps"]), ci3(r["sig2_eps_lo"], r["sig2_eps_hi"])],
            ["Share of Var(LES_it) explained by X_it", f3(r["marginal_r2"]), ci3(r["marginal_r2_lo"], r["marginal_r2_hi"])],
            ["Out-of-sample Pearson r", f3(r["oos_r"]), ci3(r["oos_r_lo"], r["oos_r_hi"])],
            ["Member-terms / members", f"{n(r['n_rows'])} / {n(r['n_members'])}", ""],
            ["Out-of-sample pairs / members", f"{n(r['oos_n_pairs'])} / {n(r['oos_n_members'])}", ""],
            ["PREREG verdict", r["prereg_verdict"], ""],
        ])
        (TAB / f"t_step3_{key}.md").write_text(tab)

    # ---- Step 4 (PREREG) ----
    cls = pd.read_stata(s4.CLASS, convert_categoricals=False,
                        columns=["law_ind", "college_law_name"] + [f"occupation{k}_category" for k in range(1, 11)])
    occ = cls[[f"occupation{k}_category" for k in range(1, 11)]].isin([1, 2, 3, 4]).any(axis=1)
    law_school = cls["college_law_name"].fillna("").astype(str).str.strip().ne("")
    assert ((cls["law_ind"] == 1) == law_school).all()
    both = s4r["class_unique_members_both_chambers"]
    V["class"] = {"rows": n(len(cls)), "law_rows": n((cls["law_ind"] == 1).sum()),
                  "deg_not_occ_rows": n(((cls["law_ind"] == 1) & ~occ).sum()),
                  "occ_not_deg_rows": n(((cls["law_ind"] == 0) & occ).sum()),
                  "people": n(both["members"]), "law_people": n(both["law_deg"]), "phd_people": n(both["phd"]),
                  "econ_people": n(both["econ_phd"]), "blank_field_people": n(both["phd_field_blank"]),
                  "matched_people": n(lr["matched_people"]), "unmatched_people": n(len(lr["unmatched_icpsr"]))}
    # Counts computed here from the raw data are saved to output/ so Step 6 can trace them.
    (OUT / "step5_data_counts.json").write_text(json.dumps({
        "house_rows_raw": int(len(raw_house)), "house_rows_no_icpsr": int(raw_house["id"].isna().sum()),
        "class_rows": int(len(cls)), "class_rows_law_ind_1": int((cls["law_ind"] == 1).sum()),
        "class_rows_degree_not_lawyer_occ": int(((cls["law_ind"] == 1) & ~occ).sum()),
        "class_rows_lawyer_occ_not_degree": int(((cls["law_ind"] == 0) & occ).sum())}, indent=2))
    count_rows = []
    for b, key in [("House", "s4house"), ("Senate", "s4senate")]:
        ch = s4r["chambers"][b]
        c = ch["counts"]
        cb = co[co["body"] == b].set_index("term")
        jd = cb.loc["law_deg"]
        V[key] = {"class_members": n(c["class_members"]), "matched": n(c["matched_to_LES"]),
                  "unmatched": n(c["unmatched"]), "law": n(c["law_degree"]), "phd": n(c["doctorate_phd_ind"]),
                  "econ": n(c["econ_phd"]), "blank": n(c["doctorate_field_blank"]),
                  "sigma_alpha": f3(c["sigma_alpha_full_panel"]),
                  "jd": f3(jd["estimate_sigma_alpha_units"]), "jd_lo": sgn3(jd["ci_lo"]), "jd_hi": sgn3(jd["ci_hi"]),
                  "verdict": ch["prereg_jd_verdict"], "dropped_terms": c["terms_dropped_lt_min_holders"] or "none"}
        count_rows.append([b, n(c["class_members"]), n(c["matched_to_LES"]), n(c["law_degree"]),
                           n(c["doctorate_phd_ind"]), n(c["econ_phd"]), n(c["female"]), n(c["black"]), n(c["hispanic"])])
        names = {"law_deg": "**Law degree**", "phd": "Doctorate", "female": "Female", "black": "Black", "hispanic": "Hispanic"}
        rows = [[names[t], sgn3(r["estimate_sigma_alpha_units"]), ci3s(r["ci_lo"], r["ci_hi"])]
                for t, r in cb.drop("Intercept").iterrows()]
        (TAB / f"t_step4_{b.lower()}.md").write_text(md_table([f"{b} (n = {n(c['matched_to_LES'])})", "Effect (σ_α units)", "95% CI"], rows))
    (TAB / "t_step4_counts.md").write_text(md_table(
        ["Chamber", "In CLASS", "Matched to LES", "Law degree", "Doctorate", "Economics PhD", "Female", "Black", "Hispanic"],
        count_rows))

    # ---- Combining rule (PREREG) ----
    kappa_ok = s3["House"]["kappa"] >= 0.20
    jd_ok = s4r["chambers"]["House"]["prereg_jd_verdict"] == "JD favors law school as a skill source"
    V["combined"] = {"kappa_ok": "met" if kappa_ok else "not met", "jd_ok": "met" if jd_ok else "not met",
                     "verdict": "not yet determined (Test C pending)" if (kappa_ok and jd_ok)
                     else "the data gives no recommendation for law school"}

    # ---- Law effects in three units (D9). Threshold and power use the full-panel σ̂_α ----
    def m(body, q):
        r = mixed.loc[(body, q)]
        return r["estimate"], r["ci_lo"], r["ci_hi"]
    E = {"matched": n(lr["matched_people"]), "unmatched": n(len(lr["unmatched_icpsr"])), "class_people": n(lr["class_people"]),
         "z": f2(lr["z_sum_80pct_power"])}
    for b in ["House", "Senate"]:
        k = b.lower()
        info = lr[b]
        E.update({f"{k}_members": n(info["n_members"]), f"{k}_rows": n(info["n_rows"]),
                  f"{k}_n_law": n(info["law_deg"]), f"{k}_n_occ": n(info["lawyer_occ"]), f"{k}_n_both": n(info["both"]),
                  f"{k}_n_deg_only": n(info["degree_not_occ"]), f"{k}_n_occ_only": n(info["occ_not_degree"]),
                  f"{k}_sigma_alpha": f3(m(b, "sigma_alpha_prereg")[0]),
                  f"{k}_thr_les": f3(0.20 * s3[b]["sigma_alpha"])})
    U = {}
    specs = [("s4", "PREREG step4 (OLS on BLUP)", "law_deg", "Law degree (PREREG Step 4)"),
             ("e1", "E1/E2 mixed model: degree", "law_deg", "E1: law degree in the mixed model"),
             ("e2", "E1/E2 mixed model: occupation", "lawyer_occ", "E2: lawyer occupation in the mixed model")]
    tab_rows = {"s4": [], "e": []}
    for b in ["House", "Senate"]:
        for tag, analysis, term, lab in specs:
            r = units[(units["body"] == b) & (units["analysis"] == analysis) & (units["term"] == term)]
            les = r[r["unit"] == "LES points"].iloc[0]
            full = r[r["unit"].str.startswith("full-panel")].iloc[0]
            samp = r[r["unit"].str.startswith("sample")].iloc[0]
            samp_sigma = float(samp["unit"].split("(")[1].rstrip(")"))
            key = f"{tag}{b[0].lower()}"
            U.update({f"{key}_les": sgn3(les["estimate"]), f"{key}_les_lo": sgn3(les["ci_lo"]), f"{key}_les_hi": sgn3(les["ci_hi"]),
                      f"{key}_full": sgn3(full["estimate"]), f"{key}_full_lo": sgn3(full["ci_lo"]), f"{key}_full_hi": sgn3(full["ci_hi"]),
                      f"{key}_samp": sgn3(samp["estimate"]), f"{key}_samp_lo": sgn3(samp["ci_lo"]), f"{key}_samp_hi": sgn3(samp["ci_hi"]),
                      f"{key}_samp_sigma": f3(samp_sigma), f"{key}_se_full": f3(full["boot_se"]),
                      f"{key}_mde_full": f3(full["mde_80pct_power"]), f"{key}_pow": f2(full["power_at_prereg_threshold"])})
            tab_rows["s4" if tag == "s4" else "e"].append([
                b, lab, f"{sgn3(les['estimate'])} {ci3s(les['ci_lo'], les['ci_hi'])}",
                f"{sgn3(full['estimate'])} {ci3s(full['ci_lo'], full['ci_hi'])}",
                f"{sgn3(samp['estimate'])} {ci3s(samp['ci_lo'], samp['ci_hi'])}",
                f3(samp_sigma), f3(full["boot_se"]), f3(full["mde_80pct_power"]), f2(full["power_at_prereg_threshold"])])
    hdr = ["Chamber", "Effect", "LES points [95% CI]", "Full-panel σ_α units [95% CI]", "Sample σ̂_α units [95% CI]",
           "Sample σ̂_α", "Bootstrap standard error (full-panel units)", "Smallest effect with 80% power (full-panel units)",
           "Power at 0.20σ_α (full-panel)"]
    (TAB / "t_step4_law_units.md").write_text(md_table(hdr, tab_rows["s4"]))
    (TAB / "t_expl_law.md").write_text(md_table(hdr, tab_rows["e"]))
    E.update(U)
    w_all, w_m = lr["econ_phd_wilson"]
    E.update({"econ_k": str(w_all["k"]), "econ_share_all": f"{100 * w_all['share']:.2f}%",
              "econ_lo_all": f"{100 * w_all['ci'][0]:.2f}%", "econ_hi_all": f"{100 * w_all['ci'][1]:.2f}%",
              "econ_share_m": f"{100 * w_m['share']:.2f}%", "econ_lo_m": f"{100 * w_m['ci'][0]:.2f}%",
              "econ_hi_m": f"{100 * w_m['ci'][1]:.2f}%"})
    h = s3["House"]
    E.update({"rank_kappa": f3(rank["kappa"]), "rank_kappa_lo": f3(rank["kappa_ci"][0]), "rank_kappa_hi": f3(rank["kappa_ci"][1]),
              "rank_r": f3(rank["oos_r"]), "rank_r_lo": f3(rank["oos_r_ci"][0]), "rank_r_hi": f3(rank["oos_r_ci"][1]),
              "rank_r2": f3(rank["marginal_r2"])})
    (TAB / "t_expl_rank.md").write_text(md_table(["House", "LES 1.0 (PREREG, primary)", "Rank-normal LES (EXPLORATORY)"], [
        ["κ [95% CI]", f"{f3(h['kappa'])} {ci3(h['kappa_lo'], h['kappa_hi'])}",
         f"{f3(rank['kappa'])} {ci3(*rank['kappa_ci'])}"],
        ["Share of Var explained by X_it [95% CI]", f"{f3(h['marginal_r2'])} {ci3(h['marginal_r2_lo'], h['marginal_r2_hi'])}",
         f"{f3(rank['marginal_r2'])} {ci3(*rank['marginal_r2_ci'])}"],
        ["Out-of-sample r [95% CI]", f"{f3(h['oos_r'])} {ci3(h['oos_r_lo'], h['oos_r_hi'])}",
         f"{f3(rank['oos_r'])} {ci3(*rank['oos_r_ci'])}"],
    ]))
    assert len(E) == len(set(E))
    V["expl"] = E
    write_yaml(V, ROOT / "_variables.yml")
    print(sum(len(v) for v in V.values()), "variables;", sorted(p.name for p in TAB.glob("*.md")))


if __name__ == "__main__":
    main()

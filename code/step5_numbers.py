def f2(x): return f"{x:.2f}"
def f3(x): return f"{x:.3f}"
def f5(x): return f"{x:.5f}"
def n(x): return f"{int(x):,}"
def ci3(lo, hi): return f"[{lo:.3f}, {hi:.3f}]"
def sgn3(x): return f"{x:+.3f}".replace("-", "−")
def ci3s(lo, hi): return f"[{sgn3(lo)}, {sgn3(hi)}]"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def write_yaml(d, path):
    lines = ["# GENERATED by code/step5_numbers.py from output/. Do not edit by hand."]
    for sec, kv in d.items():
        lines.append(f"{sec}:")
        for k, v in kv.items():
            lines.append(f'  {k}: "{v}"')
    path.write_text("\n".join(lines) + "\n")



"""Step 5: every number in post.qmd. Reads output/ (and CLASS for three row-level counts).

Writes:
  _variables.yml          values for {{< var ... >}} in post.qmd (Quarto reads it from the post's folder)
  output/tables/*.md      Markdown tables included in post.qmd

Usage: python -I step5_numbers.py
"""

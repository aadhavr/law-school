"""Write TABLE_COLUMNS.md: shape and full column list of every csv/xlsx/dta under data/raw/. Read-only."""
import warnings
from pathlib import Path
import pandas as pd
warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parent.parent
out = ["# TABLE_COLUMNS.md", "", "Generated by `code/write_table_columns.py`. Files are read-only inputs.", ""]
for f in sorted((ROOT / "data/raw").rglob("*")):
    if f.suffix.lower() not in (".csv", ".xlsx", ".dta") or f.name == "manifest.csv":
        continue
    rel = f.relative_to(ROOT)
    if f.suffix == ".csv":
        d = pd.read_csv(f, low_memory=False); cols = list(d.columns)
    elif f.suffix == ".dta":
        d = pd.read_stata(f, convert_categoricals=False); cols = list(d.columns)
    else:
        raw = pd.read_excel(f, header=None)
        title = raw.iloc[1, 0]; hdr = [str(x) for x in raw.iloc[3].tolist() if pd.notna(x)]
        d = raw; cols = [f"(title) {title}", "(column header row 4) " + ", ".join(hdr),
                         "(first column) field names; " + ("row 5 sub-headers: Number / Percent" if raw.iloc[4].astype(str).str.contains("Number").any() else "values are counts (no sub-header row)")]
    out += [f"## `{rel}`", f"{d.shape[0]} rows × {d.shape[1]} columns", "", ", ".join(f"`{c}`" for c in cols) if f.suffix != ".xlsx" else "\n".join(f"- {c}" for c in cols), ""]
(ROOT / "TABLE_COLUMNS.md").write_text("\n".join(out))
print("\n".join(l[:300] for l in out if l.startswith(("##", "- ")) or "rows ×" in l))
